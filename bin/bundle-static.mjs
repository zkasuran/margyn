/**
 * Bundles the frontend into a module the Worker can serve itself.
 *
 * Cloudflare's Workers Assets API returned a 500 with `code: -1` on every
 * attempt on 2026-08-05, across five wrangler retries and a direct call. A plain
 * script upload works, so the frontend rides along inside the script instead.
 *
 * That is not a workaround so much as the right shape for this app: the frontend
 * is two files and no build step, well inside the 3 MB script limit, and one
 * upload means the page and the API can never be deployed at different versions.
 *
 * Run `npm run worker:bundle` after touching anything in web/public.
 */
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, extname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const PUBLIC = join(here, "..", "web", "public");
const OUT = join(here, "..", "worker", "static.generated.mjs");

const MIME = {
  ".html": "text/html; charset=utf-8",
  ".mjs": "text/javascript; charset=utf-8",
  ".js": "text/javascript; charset=utf-8",
  ".css": "text/css; charset=utf-8",
  ".json": "application/json",
  ".svg": "image/svg+xml",
  ".ico": "image/x-icon",
};

const files = readdirSync(PUBLIC, { withFileTypes: true })
  .filter((e) => e.isFile())
  .map((e) => e.name)
  .sort();

const entries = files.map((name) => {
  const body = readFileSync(join(PUBLIC, name), "utf8");
  const type = MIME[extname(name)] ?? "application/octet-stream";
  // JSON.stringify is the escaping: the bodies contain backticks, ${...} and
  // quotes, and a template literal would let the page inject itself into this
  // module.
  return `  "/${name}": { type: ${JSON.stringify(type)}, body: ${JSON.stringify(body)} },`;
});

const generated = `/**
 * GENERATED by bin/bundle-static.mjs. Do not edit.
 * Source: web/public/. Regenerate with \`npm run worker:bundle\`.
 */
export const STATIC = {
${entries.join("\n")}
};
`;

writeFileSync(OUT, generated);
const bytes = Buffer.byteLength(generated);
console.log(`bundled ${files.length} file${files.length === 1 ? "" : "s"} into worker/static.generated.mjs (${bytes} bytes)`);
for (const name of files) console.log(`  /${name}`);
if (bytes > 2_500_000) {
  console.error("bundle is close to the 3 MB script limit, so the assets API is worth revisiting");
  process.exitCode = 1;
}
