/**
 * Bundles the frontend into a module the Worker serves itself.
 *
 * Cloudflare's Workers Assets API returned a 500 with `code: -1` on every attempt
 * on 2026-08-05, across five wrangler retries and a direct call, so the frontend
 * rides inside the script instead. That turned out to be the right shape anyway:
 * one upload means the page and the API can never be deployed at different
 * versions.
 *
 * Text and binary are read differently on purpose. An earlier version read every
 * file as utf8, which silently destroyed both PNGs: bytes that are not valid utf8
 * become U+FFFD, so `og.png` went in at 13,445 bytes and came out as 12,703
 * characters. Nothing threw. The page would have served a corrupt image and the
 * link preview would have been broken on every platform that fetched it. That is
 * the exact defect class this product exists to find, so the fidelity is now
 * asserted by test/bundle.test.mjs rather than assumed.
 *
 * Run `npm run worker:bundle` after touching anything in web/public.
 */
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, extname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const PUBLIC = join(here, "..", "web", "public");
const OUT = join(here, "..", "worker", "static.generated.mjs");

/** Every extension the page serves, with the type and how to encode it. */
export const TYPES = {
  ".html": { type: "text/html; charset=utf-8", binary: false },
  ".mjs": { type: "text/javascript; charset=utf-8", binary: false },
  ".js": { type: "text/javascript; charset=utf-8", binary: false },
  ".css": { type: "text/css; charset=utf-8", binary: false },
  ".json": { type: "application/json", binary: false },
  ".txt": { type: "text/plain; charset=utf-8", binary: false },
  ".xml": { type: "application/xml; charset=utf-8", binary: false },
  ".svg": { type: "image/svg+xml", binary: false },
  ".png": { type: "image/png", binary: true },
  ".ico": { type: "image/x-icon", binary: true },
  ".webp": { type: "image/webp", binary: true },
};

const files = readdirSync(PUBLIC, { withFileTypes: true })
  .filter((e) => e.isFile())
  .map((e) => e.name)
  .sort();

const rows = [];
let bytes = 0;
for (const name of files) {
  const spec = TYPES[extname(name)];
  if (!spec) throw new Error(`no type known for ${name}, so it would ship as octet-stream`);
  const raw = readFileSync(join(PUBLIC, name));
  bytes += raw.length;
  // JSON.stringify does the escaping. A template literal would let the page body,
  // which contains backticks and ${...}, inject itself into this module.
  const body = spec.binary ? raw.toString("base64") : raw.toString("utf8");
  rows.push(
    `  "/${name}": { type: ${JSON.stringify(spec.type)}, binary: ${spec.binary}, ` +
      `bytes: ${raw.length}, body: ${JSON.stringify(body)} },`,
  );
}

const generated = `/**
 * GENERATED by bin/bundle-static.mjs. Do not edit.
 * Source: web/public/. Regenerate with \`npm run worker:bundle\`.
 *
 * \`binary: true\` means \`body\` is base64 and the worker decodes it before
 * responding. \`bytes\` is the length on disk, so a corrupted entry is detectable
 * rather than merely wrong.
 */
export const STATIC = {
${rows.join("\n")}
};
`;

writeFileSync(OUT, generated);
const total = Buffer.byteLength(generated);
console.log(`bundled ${files.length} files, ${bytes} bytes of assets into ${total} bytes of module`);
for (const name of files) {
  const spec = TYPES[extname(name)];
  console.log(`  /${name.padEnd(22)} ${spec.type.padEnd(30)} ${spec.binary ? "base64" : "utf8"}`);
}
if (total > 2_500_000) {
  console.error("bundle is near the 3 MB script limit, so the assets API is worth revisiting");
  process.exitCode = 1;
}
